// ---- Development check for longer translations ----
// Open any page with ?pseudo in the address (development only) to make every
// string about 30% longer, roughly how much longer French usually is.
// Layouts should still hold. Placeholders like {count} are kept intact.
const NOT_COPY = new Set(['id', 'to', 'photos']) // ids, link paths and image paths

function stretch(node) {
  for (const key of Object.keys(node)) {
    const value = node[key]
    if (NOT_COPY.has(key)) continue
    if (typeof value === 'string') {
      const extra = Math.max(2, Math.round(value.length * 0.3))
      node[key] = `${value} ${'ø'.repeat(extra)}`
    } else if (value && typeof value === 'object') {
      stretch(value)
    }
  }
}

if (
  import.meta.env?.DEV &&
  typeof window !== 'undefined' &&
  window.location &&
  new URLSearchParams(window.location.search).has('pseudo')
) {
  stretch(en)
}
